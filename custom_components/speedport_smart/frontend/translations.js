export const PANEL_TRANSLATIONS = Object.freeze({
  en: Object.freeze(ENGLISH),
  de: Object.freeze(GERMAN),
});

export function resolvePanelLanguage(hass, browserLanguage = "en") {
  const requested =
    hass?.language || hass?.locale?.language || browserLanguage || "en";
  const language = String(requested).toLowerCase().split(/[-_]/, 1)[0];
  return Object.hasOwn(PANEL_TRANSLATIONS, language) ? language : "en";
}

export function panelTranslate(language, key, replacements = {}) {
  const translations = PANEL_TRANSLATIONS[language] || PANEL_TRANSLATIONS.en;
  const template = translations[key] ?? PANEL_TRANSLATIONS.en[key] ?? key;
  return template.replace(/\{([a-z0-9_]+)\}/gi, (_match, name) =>
    Object.hasOwn(replacements, name) ? String(replacements[name]) : `{${name}}`,
  );
}

export function formatPanelDurationSeconds(value, locale, language) {
  const numeric = Number(value);
  if (!Number.isFinite(numeric) || numeric < 0) return undefined;
  let remaining = Math.floor(numeric);
  if (remaining === 0) {
    return `0 ${panelTranslate(language, "duration.second")}`;
  }

  const formatter = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
  const units = [
    ["duration.day", 86_400],
    ["duration.hour", 3_600],
    ["duration.minute", 60],
    ["duration.second", 1],
  ];
  const parts = [];
  for (const [key, seconds] of units) {
    const amount = Math.floor(remaining / seconds);
    remaining %= seconds;
    if (amount > 0) {
      parts.push(`${formatter.format(amount)} ${panelTranslate(language, key)}`);
    }
    if (parts.length === 2) break;
  }
  return parts.join(" ");
}
